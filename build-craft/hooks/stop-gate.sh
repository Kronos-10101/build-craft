#!/usr/bin/env bash
# stop-gate.sh — OPTIONAL Claude Code Stop hook for build-craft.
#
# Purpose: when a session tries to stop, re-run the build-craft craft gate
# for the furthest phase the run has reached. If that gate fails, block the
# stop (exit 2) and feed the gate output back to the model on stderr, so the
# session keeps working instead of ending on an ungated run.
#
# Contract:
#   - The run directory comes from the BUILD_CRAFT_RUN_DIR environment
#     variable (see hooks/README.md).
#   - If BUILD_CRAFT_RUN_DIR is unset or empty, this hook is a no-op and
#     exits 0 immediately, so installing it never breaks unrelated work.
#   - If the Stop payload says stop_hook_active is true, exit 0: Claude Code
#     sets that flag when a Stop hook has already blocked once, and honouring
#     it is what prevents an infinite stop loop.
#
# Phase detection heuristic (deliberately simple — the gate itself does the
# real checking; this only picks which phase to check):
#   report.md exists            -> p4 (verification/report phase reached)
#   else progress.md exists     -> p3 (build tracking has started)
#   else grill.md or design.md  -> p2 (plan is being grilled / designed)
#   else                        -> p1 (only the plan scaffold, or nothing)

# No `set -e`: a failing gate is an expected branch handled explicitly
# below, not a shell error.

run_dir="${BUILD_CRAFT_RUN_DIR:-}"

# Safety property: no run dir configured means build-craft is not in play
# for this session, so never block stopping.
if [ -z "$run_dir" ]; then
    exit 0
fi

# Read the Stop hook payload from stdin exactly once; it is needed for the
# stop_hook_active check below.
payload="$(cat)"

# Loop guard: parse stdin minimally with a whitespace-tolerant grep for the
# boolean flag rather than pulling in a full JSON parser for one field.
# The payload is machine-generated by Claude Code, so the key order and
# spelling are stable; the pattern tolerates spacing around the colon.
if printf '%s' "$payload" | grep -Eq '"stop_hook_active"[[:space:]]*:[[:space:]]*true'; then
    exit 0
fi

# Pick the highest phase with artifacts present (heuristic documented in the
# header comment above).
if [ -f "$run_dir/report.md" ]; then
    phase="p4"
elif [ -f "$run_dir/progress.md" ]; then
    phase="p3"
elif [ -f "$run_dir/grill.md" ] || [ -f "$run_dir/design.md" ]; then
    phase="p2"
else
    phase="p1"
fi

# Locate craft-gate.mjs relative to this script: hooks/ sits inside the
# skill directory, so the gate is at ../scripts/craft-gate.mjs from here.
# Resolve both directories to canonical absolute paths (pwd -P) so the hook
# works from any working directory, with no hardcoded home paths.
hook_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
skill_dir="$(cd -- "$hook_dir/.." && pwd -P)"
gate="$skill_dir/scripts/craft-gate.mjs"

if [ ! -f "$gate" ]; then
    printf 'build-craft stop gate: cannot block stop — craft gate not found at %s. Fix: reinstall the build-craft skill so scripts/craft-gate.mjs sits next to hooks/.\n' "$gate" >&2
    exit 2
fi

# Run the gate for the detected phase, capturing combined output so a
# failure can be relayed verbatim. The gate's current CLI takes the run
# directory via --dir.
gate_output="$(node "$gate" --phase "$phase" --dir "$run_dir" 2>&1)"
gate_status=$?

if [ "$gate_status" -eq 0 ]; then
    exit 0
fi

# Block stopping: for Stop hooks Claude Code treats exit 2 as "block" and
# feeds stderr back to the model. Prefix the raw gate output with one line
# naming the failing phase and the fix.
{
    printf 'build-craft stop gate: phase %s gate FAILED for run dir %s. Fix: address the gate failures below, then re-run: node %s --phase %s --dir %s\n' "$phase" "$run_dir" "$gate" "$phase" "$run_dir"
    printf '%s\n' "$gate_output"
} >&2
exit 2
